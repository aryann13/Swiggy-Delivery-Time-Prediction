# In production software and MLOps, we enforce a Data Contract at the API gateway:

# Any data entering the application MUST conform to a strict schema.
# If a request is missing fields or sends strings instead of floats,
# it must fail immediately at the door before touching any machine learning code.

# This prevents "Garbage In, Garbage Out" and ensures that only clean, valid data is processed by your model.
# define the schema of the incoming request using pydantic

# Define the schema of the incoming request using Pydantic
class Data(BaseModel):  
    ID: str
    Delivery_person_ID: str
    Delivery_person_Age: str
    Delivery_person_Ratings: str
    Restaurant_latitude: float
    Restaurant_longitude: float
    Delivery_location_latitude: float
    Delivery_location_longitude: float
    Order_Date: str
    Time_Orderd: str
    Time_Order_picked: str
    Weatherconditions: str
    Road_traffic_density: str
    Vehicle_condition: int
    Type_of_order: str
    Type_of_vehicle: str
    multiple_deliveries: str
    Festival: str
    City: str

def load_model_information(file_path):
    """Loads the run_information.json generated by evaluation stage."""
    with open(file_path) as f:
        run_info = json.load(f)
    return run_info

def load_transformer(transformer_path):
    transformer = joblib.load(transformer_path)
    return transformer

# columns expected by the preprocessor
num_cols = ["age", "ratings", "pickup_time_minutes", "distance"]
nominal_cat_cols = [
    'weather', 'type_of_order', 'type_of_vehicle', 
    "festival", "city_type", "is_weekend", "order_time_of_day"
]
ordinal_cat_cols = ["traffic", "distance_type"]

# ---------------------------------------------------------
# Model & Preprocessor Loading (Executed ONCE at Startup)
# ---------------------------------------------------------
# 1. Load the trained model (prioritize fast local model, fallback to MLflow registry)
local_model_path = "models/model.joblib"
if os.path.exists(local_model_path):
    model = joblib.load(local_model_path)
    print("Loaded model from local models/model.joblib")
else:
    try:
        client = MlflowClient()
        model_name = load_model_information("run_information.json")['model_name']
        stage = "Staging"
        model_path = f"models:/{model_name}/{stage}"
        model = mlflow.sklearn.load_model(model_path)
        print(f"Loaded model '{model_name}' (Stage: {stage}) from MLflow Registry")
    except Exception as e:
        print(f"Registry load failed ({e}), loading local models/model.joblib")
        model = joblib.load("models/model.joblib")

# 5. Load the fitted preprocessor
preprocessor_path = "models/preprocessor.joblib"
preprocessor = load_transformer(preprocessor_path)

# 6. Build the unified end-to-end inference pipeline
model_pipe = Pipeline(steps=[
    ('preprocess', preprocessor),
    ('regressor', model)
])

# create the FastAPI app instance
app = FastAPI(
    title="Swiggy Delivery Time Prediction API",
    description="Production REST API to predict food delivery time using Stacking Regressor (RF + XGBoost)",
    version="1.0.0"
)

# Mount static files (CSS, JS) and configure Jinja2 templates
app.mount("/static", StaticFiles(directory="static"), name="static")
templates = Jinja2Templates(directory="templates")

#  Endpoint 1: Home — renders the prediction UI
@app.get(path="/")
def home(request: Request):
    return templates.TemplateResponse(request, "index.html")

#Endpoint 2: Prediction Endpoint
@app.post(path="/predict")
def do_predictions(data: Data):
    # 1. Convert incoming Pydantic data into a 1-row DataFrame
    pred_data = pd.DataFrame({
        'ID': data.ID,
        'Delivery_person_ID': data.Delivery_person_ID,
        'Delivery_person_Age': data.Delivery_person_Age,
        'Delivery_person_Ratings': data.Delivery_person_Ratings,
        'Restaurant_latitude': data.Restaurant_latitude,
        'Restaurant_longitude': data.Restaurant_longitude,
        'Delivery_location_latitude': data.Delivery_location_latitude,
        'Delivery_location_longitude': data.Delivery_location_longitude,
        'Order_Date': data.Order_Date,
        'Time_Orderd': data.Time_Orderd,
        'Time_Order_picked': data.Time_Order_picked,
        'Weatherconditions': data.Weatherconditions,
        'Road_traffic_density': data.Road_traffic_density,
        'Vehicle_condition': data.Vehicle_condition,
        'Type_of_order': data.Type_of_order,
        'Type_of_vehicle': data.Type_of_vehicle,
        'multiple_deliveries': data.multiple_deliveries,
        'Festival': data.Festival,
        'City': data.City
    }, index=[0])

    # 2. Clean the raw input and extract features (distance, pickup time, etc.)
    cleaned_data = perform_data_cleaning(pred_data)
    # 3. Predict delivery time via our unified pipeline (preprocessor + model)
    predictions = model_pipe.predict(cleaned_data)[0]
    return round(float(predictions), 2)

